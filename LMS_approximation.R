LMS_parameter <- function(SEX, AGE, ZSCORE) {
  # --- Calculate WT from approximated LMS formula, R script LMS_approximations.R  
  # male, SEX=1
  if(SEX == 1) {
    L1_1 = 0.2473
    L1_2 = -0.01914
    L1_3 = 0.0004106
    L1_4 = -0.000003433
    L1_5 = 0
    L1_6 = 0
    
    L2_1 = 0.0379
    L2_2 = 0.006517
    L2_3 = -0.0002416
    L2_4 = 0.00000114
    
    L3_1 = 37.76
    L3_2 = -1.039
    L3_3 = 0.01001
    L3_4 = -0.00004116
    L3_5 = 0.00000006124
    
    S1_1 = 0.1462
    S1_2 = -0.01461
    S1_3 = 0.001932
    S1_4 = -0.00008632
    
    S2_1 = 0.1114
    S2_2 = -0.0007144
    S2_3 = 0.00005574
    S2_4 = -0.000001045
    S2_5 = 0.000000007091
    
    S3_1 = 0.1001
    S3_2 = 0.001006
    S3_3 = -0.00001287
    S3_4 = 0.00000007423
    
    S4_1 = 0.03601
    S4_2 = -0.004196
    S4_3 = 0.0001062
    S4_4 = -0.0000006664
    S4_5 = 0.000000001284
    
    M_1= 4.904809
    M_2= 0.4209516
    M_3= -0.005652092
    M_4= 0.0000459995
    M_5= -0.00000010448529
  }
  else {
    L1_1 = 0.2894
    L1_2 = -0.08659
    L1_3 = 0.005358
    L1_4 = -0.0001654
    L1_5 = 0.00000245
    L1_6 = -0.00000001386
    
    L2_1 = -0.1719
    L2_2 = -0.006149
    L2_3 = 0.00002171
    L2_4 = 0
    
    L3_1 = 21.71
    L3_2 = -0.6754
    L3_3 = 0.007321
    L3_4 = -0.00003391
    L3_5 = 0.00000005628
    
    S1_1 = 0.1424
    S1_2 = -0.007525
    S1_3 = 0.0008634
    S1_4 = -0.00003018
    
    S2_1 = 0.1191
    S2_2 = 0.0006519
    S2_3 = -0.00004486
    S2_4 = 0.000001349
    S2_5 = -0.00000001082
    
    S3_1 = 0.1012
    S3_2 = 0.0007674
    S3_3 = -0.000001416
    S3_4 = 0
    
    S4_1 = -0.2138
    S4_2 = 0.004139
    S4_3 = 0.00001957
    S4_4 = -0.0000003040
    S4_5 = 0.0000000007493
    
    M_1= 4.832
    M_2= 0.3743
    M_3= -0.004874
    M_4= 0.00004466
    M_5= -0.0000001167
  }
  
  # AGE in months
  if(AGE <= 60) {
    L = L1_1  + L1_2*AGE  + L1_3*(AGE**2) + L1_4*(AGE**3) + L1_5*(AGE**4) + L1_6*(AGE**5)
  }
  else if(AGE > 60 & AGE <= 120) {
    L = L2_1  + L2_2*AGE  + L2_3*(AGE**2) + L2_4*(AGE**3) 
  }
  else{
    L = L3_1  + L3_2*AGE  + L3_3*(AGE**2) + L3_4*(AGE**3) + L3_5*(AGE**4) 
  }
  
  if(AGE <= 8) {
    SX = S1_1  + S1_2*AGE  + S1_3*(AGE**2) + S1_4*(AGE**3) 
  }
  else if(AGE > 8 & AGE <= 60) {
    SX = S2_1  + S2_2*AGE  + S2_3*(AGE**2) + S2_4*(AGE**3) + S2_5*(AGE**4) 
  }
  else if(AGE > 60 & AGE <= 120) {
    SX = S3_1  + S3_2*AGE  + S3_3*(AGE**2) + S3_4*(AGE**3) 
  }
  else{
    SX = S4_1  + S4_2*AGE  + S4_3*(AGE**2) + S4_4*(AGE**3) + S4_5*(AGE**4) 
  }
  
  M = M_1  + M_2*AGE  + M_3*(AGE**2) + M_4*(AGE**3) + M_5*(AGE**4)
  
  # corrected for TB 
  CORR_MM = 0.95 - 0.30/(1+exp(-0.4*(AGE/12-6)))
  
  # Calculate WT in kg from predicted L,M and S values
  WTSIM = M*CORR_MM*((ZSCORE*L*SX)+1)**(1/L)
  
  return(WTSIM)
}